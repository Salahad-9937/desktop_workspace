/// Направления ручного изменения геометрического размера окна.
enum ResizeHandle {
  /// Северная грань (верх).
  n,

  /// Южная грань (низ).
  s,

  /// Восточная грань (право).
  e,

  /// Западная грань (лево).
  nw,

  /// Северо-восточный угол.
  ne,

  /// Северо-западный угол.
  w,

  /// Юго-восточный угол.
  se,

  /// Юго-западный угол.
  sw,
}

/// Зоны магнитного прилипания окна к границам рабочего стола (Quick Tile).
enum SnapZone {
  /// Прилипание не активно.
  none,

  /// Левая вертикальная половина экрана.
  left,

  /// Правая вертикальная половина экрана.
  right,

  /// Развертывание на всю доступную рабочую область.
  maximize,

  /// Верхняя левая четверть экрана.
  topLeft,

  /// Верхняя правая четверть экрана.
  topRight,

  /// Нижняя левая четверть экрана.
  bottomLeft,

  /// Нижняя правая четверть экрана.
  bottomRight,
}