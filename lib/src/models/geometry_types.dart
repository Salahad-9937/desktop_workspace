/// Высота нижней панели задач (Taskbar) в логических пикселях.
const double kTaskbarHeight = 42.0;

/// Дистанция магнитного прилипания к границам экрана и соседним окнам (px).
const double kMagnetThreshold = 10.0;

/// Дистанция активации краевых зон быстрого тайлинга (px).
const double kEdgeSnapTriggerZone = 52.0;

/// Минимально допустимая ширина окна в пикселях.
const double kMinWindowWidth = 320.0;

/// Минимально допустимая высота окна в пикселях.
const double kMinWindowHeight = 180.0;

/// Максимально допустимый геометрический размер окна в пикселях.
const double kMaxWindowExtent = 4000.0;

/// Направления ручного изменения геометрического размера окна.
enum ResizeHandle {
  /// Северная грань (верх).
  n,

  /// Южная грань (низ).
  s,

  /// Восточная грань (право).
  e,

  /// Западная грань (лево).
  w,

  /// Северо-восточный угол.
  ne,

  /// Северо-западный угол.
  nw,

  /// Юго-восточный угол.
  se,

  /// Юго-западный угол.
  sw,
}

/// Зоны магнитного прилипания окна к границам рабочего стола (Quick Tile).
enum SnapZone {
  /// Прилипание не активно.
  none,

  /// Левая вертикальная половина экрана.
  left,

  /// Правая вертикальная половина экрана.
  right,

  /// Развертывание на всю доступную рабочую область.
  maximize,

  /// Верхняя левая четверть экрана.
  topLeft,

  /// Верхняя правая четверть экрана.
  topRight,

  /// Нижняя левая четверть экрана.
  bottomLeft,

  /// Нижняя правая четверть экрана.
  bottomRight,
}
